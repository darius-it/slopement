// Command gen writes the list of the open source software slopement is built
// from: every Go module that ends up in a build for macOS, Windows or Linux,
// with its version, its license and the license's full text. It writes
// internal/licenses/notices.json (embedded in the app, shown in Settings → About)
// and THIRD_PARTY_NOTICES.md (shipped with releases).
//
// Run it from the repository root after changing go.mod:
//
//	go run ./internal/licenses/gen
//
// The license names are recognised from the license texts; a module whose text
// is not recognised is written as "Unknown" and the command says so, so that it
// is looked at by hand and added to internal/licenses/classify.go.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"slopement/internal/licenses"
)

func main() {
	mods := map[string]*licenses.Notice{}
	for _, goos := range []string{"darwin", "linux", "windows"} {
		cmd := exec.Command("go", "list", "-deps", "-f", `{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}`, ".")
		cmd.Env = append(os.Environ(), "GOOS="+goos, "GOFLAGS=-tags=goolm", "CGO_ENABLED=0")
		out, err := cmd.Output()
		if err != nil {
			fatal("go list for %s: %v", goos, err)
		}
		for _, line := range strings.Split(string(out), "\n") {
			parts := strings.Split(strings.TrimSpace(line), "|")
			if len(parts) != 3 || parts[0] == "" || parts[0] == "slopement" {
				continue
			}
			if _, done := mods[parts[0]]; done {
				continue
			}
			n, err := notice(parts[0], parts[1], parts[2])
			if err != nil {
				fatal("%s: %v", parts[0], err)
			}
			mods[parts[0]] = n
		}
	}
	var all []licenses.Notice
	var unknown []string
	for _, n := range mods {
		if n.License == "Unknown" {
			unknown = append(unknown, n.Name)
		}
		all = append(all, *n)
	}
	sort.Slice(all, func(i, j int) bool { return strings.ToLower(all[i].Name) < strings.ToLower(all[j].Name) })

	data, err := json.MarshalIndent(all, "", " ")
	if err != nil {
		fatal("%v", err)
	}
	must(os.WriteFile(filepath.Join("internal", "licenses", "notices.json"), data, 0o644))
	must(os.WriteFile("THIRD_PARTY_NOTICES.md", []byte(markdown(all)), 0o644))
	fmt.Printf("%d modules written\n", len(all))
	for _, u := range unknown {
		fmt.Println("license not recognised:", u)
	}
	for _, n := range all {
		if licenses.Copyleft(n.License) {
			fmt.Println("COPYLEFT:", n.Name, n.License)
		}
	}
}

// notice reads a module's license files.
func notice(name, version, dir string) (*licenses.Notice, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var texts []string
	var kinds []string
	for _, e := range entries {
		up := strings.ToUpper(e.Name())
		if e.IsDir() || !(strings.HasPrefix(up, "LICENSE") || strings.HasPrefix(up, "LICENCE") || strings.HasPrefix(up, "COPYING") ||
			strings.HasPrefix(up, "UNLICENSE") || strings.HasPrefix(up, "PATENTS") || strings.HasPrefix(up, "NOTICE")) {
			continue
		}
		// A list of other software's licenses, or a logo's, is not the code's.
		if strings.Contains(up, "3RD-PARTY") || strings.Contains(up, "THIRD") || strings.Contains(up, "LOGO") {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		text := strings.TrimSpace(string(b))
		texts = append(texts, text)
		if !strings.HasPrefix(up, "PATENTS") && !strings.HasPrefix(up, "NOTICE") {
			kinds = append(kinds, licenses.Classify(text))
		}
	}
	n := &licenses.Notice{Name: name, Version: version, URL: "https://pkg.go.dev/" + name, Text: strings.Join(texts, "\n\n---\n\n")}
	n.License = licenses.Combine(kinds)
	return n, nil
}

func markdown(all []licenses.Notice) string {
	var b strings.Builder
	b.WriteString("# Third-party notices\n\nslopement is built with the open source software below. Its licenses are reproduced as the authors wrote them.\n")
	b.WriteString("This file is generated by `go run ./internal/licenses/gen`; do not edit it by hand.\n\n")
	b.WriteString("| Module | Version | License |\n|---|---|---|\n")
	for _, n := range all {
		fmt.Fprintf(&b, "| [%s](%s) | %s | %s |\n", n.Name, n.URL, n.Version, n.License)
	}
	for _, n := range all {
		fmt.Fprintf(&b, "\n## %s %s — %s\n\n```\n%s\n```\n", n.Name, n.Version, n.License, n.Text)
	}
	return b.String()
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(f string, a ...any) {
	fmt.Fprintf(os.Stderr, f+"\n", a...)
	os.Exit(1)
}
